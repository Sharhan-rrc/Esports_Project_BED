/**
 * Integrity red flags detected by AI
 */
export interface IntegrityFlag {
  flag: "kdRatioSpike" | "winRateSpike" | "suspiciousConsistency" | "blacklistHistory" | "reportedViolations";
  severity: "low" | "medium" | "high";
  reason: string;
  detectedAt: Date;
}

/**
 * AI-generated integrity investigation case
 */
export interface IntegrityCase {
  id: string;
  playerId: string;
  playerUsername: string;
  playerEmail: string;
  riskScore: number; // 0-100 (AI calculated)
  riskLevel: "low" | "medium" | "high";
  flags: IntegrityFlag[];
  aiAnalysis: string; // Generated by Ollama (LLM explanation)
  status: "open" | "investigating" | "resolved" | "false_positive";
  recommendedAction: "warn" | "monitor" | "temporary_ban" | "blacklist" | "clear";
  adminNotes?: string;
  resolvedBy?: string; // uid of admin who resolved
  resolvedAt?: Date;
  createdAt: Date;
  updatedAt: Date;
}

/**
 * Scan request payload
 */
export interface ScanPlayerRequest {
  playerId: string;
}

/**
 * Integrity case update payload
 */
export interface UpdateIntegrityCaseRequest {
  status: "open" | "investigating" | "resolved" | "false_positive";
  adminNotes?: string;
  recommendedAction?: "warn" | "monitor" | "temporary_ban" | "blacklist" | "clear";
}
